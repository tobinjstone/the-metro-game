// Regenerates station-coords.js from data/wmata-stations.json (WMATA API "Stations" dump).
//   node scripts/build-station-coords.mjs
import fs from 'fs';

const root = new URL('../', import.meta.url);
const { Stations } = JSON.parse(fs.readFileSync(new URL('data/wmata-stations.json', root), 'utf8'));

const coords = {};
for (const s of Stations) coords[s.Name] ??= [+s.Lat.toFixed(6), +s.Lon.toFixed(6)];   // first platform wins

const body = Object.entries(coords).sort(([a], [b]) => a.localeCompare(b))
  .map(([name, [lat, lng]]) => `  ${JSON.stringify(name)}: [${lat}, ${lng}]`).join(',\n');
fs.writeFileSync(new URL('station-coords.js', root),
`/* Generated by scripts/build-station-coords.mjs from data/wmata-stations.json — do not edit.
   Keys are WMATA API station names (the same keys places.json uses). [lat, lng] */
export const STATION_COORDS = {
${body}
};
`);
console.log(`wrote ${Object.keys(coords).length} stations`);
